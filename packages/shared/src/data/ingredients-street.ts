export function getIngredientsBySlot(tier: TierId, slot: SlotType): Ingredient[] {
  if (tier === 'STREET') {
    return STREET_INGREDIENTS.filter((i) => i.slot === slot);
  }
  return [];
}

export function getBasicIngredientForSlot(tier: TierId, slot: SlotType): Ingredient {
  const ingredients = getIngredientsBySlot(tier, slot);
  const basic = ingredients.find((i) => i.isBasic);
  if (!basic) {
    throw new Error(`No basic ingredient found for tier/slot: ${tier}/${slot}`);
  }
  return basic;
}
